"""v2 policy: router.policy.json (repo root, committed) -> compiled router_policy.py / routerPolicy.ts beside each vendored runtime.

Validation and precedence are the runtime's own (router_migrate/runtime/router_runtime.py: policy_valid, policy_for), so the
CLI and the shipped code can never disagree. Semantics: router_migrate/schemas/CONTRACTS.md section 1.
"""
import hashlib
import json
import os

from .runtime import router_runtime as _rt

POLICY_FILE = "router.policy.json"
PY_NAME = "router_policy.py"
TS_NAME = "routerPolicy.ts"
HEADER = "router-migrate compiled policy"

policy_valid = _rt.policy_valid
policy_for = _rt.policy_for


def canonical(p):
    return json.dumps(p, sort_keys=True, separators=(",", ":"))


def policy_hash(p):
    return hashlib.sha256(canonical(p).encode()).hexdigest()


def load(root):
    """(policy or None, error or None) from <root>/router.policy.json."""
    path = os.path.join(root, POLICY_FILE)
    if not os.path.exists(path):
        return None, None
    try:
        p = json.load(open(path))
    except ValueError as e:
        return None, "invalid JSON: %s" % e
    if not policy_valid(p):
        return None, "invalid policy (allowed keys: allow_flex_tier, prompt_cache_key, metadata, fallbacks, provider_timeout, service_tier, model_map, drop_params; version 1)"
    return p, None


def compile_py(p):
    return ("# %s (generated by `router-migrate apply --decisions` from router.policy.json; do not edit, re-run apply)\n"
            "# The vendored router_runtime.py imports this module. Delete it (or set ROUTER_MIGRATE_POLICY=off) for v1 behaviour.\n"
            "import json\n\nPOLICY = json.loads(%r)\nPOLICY_HASH = %r\n") % (HEADER, canonical(p), policy_hash(p))


def compile_ts(p):
    return ("// %s (generated by `router-migrate apply --decisions` from router.policy.json; do not edit, re-run apply)\n"
            "// Importing this module installs the policy for the vendored routerRuntime. Delete it for v1 behaviour.\n"
            "export const POLICY = %s;\nexport const POLICY_HASH = %s;\n"
            "(globalThis as any).__ROUTER_MIGRATE_POLICY__ = { policy: POLICY, hash: POLICY_HASH };\n") % (HEADER, canonical(p), json.dumps(policy_hash(p)))


def compiled_hash(path):
    """POLICY_HASH recorded in a compiled module, or None."""
    try:
        src = open(path).read()
    except OSError:
        return None
    if HEADER not in src:
        return None
    for line in src.splitlines():
        if line.startswith("POLICY_HASH = ") or line.startswith("export const POLICY_HASH = "):
            return line.split("=", 1)[1].strip().strip(";").strip().strip("'\"")
    return None


def write_compiled(root, p, runtime_files):
    """Write the compiled module next to each vendored runtime. Returns the list of written paths (repo-relative)."""
    out = []
    for rt in runtime_files:
        d = os.path.dirname(os.path.join(root, rt))
        if rt.endswith(".py"):
            dst, src = os.path.join(d, PY_NAME), compile_py(p)
        else:
            dst, src = os.path.join(d, TS_NAME), compile_ts(p)
        open(dst, "w").write(src)
        out.append(os.path.relpath(dst, root))
    return out


def merge_entry(p, scope, entry):
    """Add `entry` under scope ('defaults' | ('features', id) | ('globs', pattern)) of policy p (created if None)."""
    p = p or {"version": 1}
    if scope == "defaults":
        tgt = p.setdefault("defaults", {})
    else:
        kind, name = scope
        tgt = p.setdefault(kind, {}).setdefault(name, {})
    for k, v in entry.items():
        if k == "metadata":
            tgt.setdefault("metadata", {}).update(v)
        else:
            tgt[k] = v
    return p
